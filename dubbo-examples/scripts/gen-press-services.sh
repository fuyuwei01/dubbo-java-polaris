#!/usr/bin/env bash
# Generate / scale N Dubbo press services.
#
#   - interfaces  -> dubbo-api-example      (package ...example.api.press)
#   - impls       -> dubbo-quickstart-provider (package ...provider.press)
#
# Padding is NOT generated as source. Edit PressMetadataPadding.DEFAULT_BYTES,
# or pass -Dpress.metadata.bytes / PRESS_METADATA_BYTES; PressMetadataInjector
# fills URL parameters at export time.
#
# Usage:
#   ./gen-press-services.sh gen <n>   generate exactly n services (scales up or down)
#   ./gen-press-services.sh count     show how many services are currently generated
#   ./gen-press-services.sh clean     remove generated PressService* sources only
#   ./gen-press-services.sh build     compile the two modules
#
# Env (runtime, not generation):
#   PRESS_METADATA_BYTES  padding size per service, default 525312 (512KB + 1KB)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXAMPLES_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
REPO_ROOT="$(cd "${EXAMPLES_DIR}/.." && pwd)"

API_MODULE="dubbo-examples/dubbo-api-example"
PROVIDER_MODULE="dubbo-examples/dubbo-quickstart-example/dubbo-quickstart-provider"
API_PRESS_DIR="${REPO_ROOT}/${API_MODULE}/src/main/java/com/tencent/polaris/dubbo/example/api/press"
PROVIDER_PRESS_DIR="${REPO_ROOT}/${PROVIDER_MODULE}/src/main/java/com/tencent/polaris/dubbo/quickstart/example/provider/press"

API_PACKAGE="com.tencent.polaris.dubbo.example.api.press"
PROVIDER_PACKAGE="com.tencent.polaris.dubbo.quickstart.example.provider.press"

usage() {
  sed -n '2,19p' "$0"
  exit 1
}

