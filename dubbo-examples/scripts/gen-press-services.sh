service_name() {
  printf 'PressService%04d' "$1"
}

generate_interface() {
  local index name file
  index="$1"
  name="$(service_name "${index}")"
  file="${API_PRESS_DIR}/${name}.java"
  {
    license_header
    cat <<EOF

package ${API_PACKAGE};

/**
 * Generated by dubbo-examples/scripts/gen-press-services.sh - do not edit.
 */
public interface ${name} {

    String echo(String value);
}
EOF
  } >"${file}"
}

generate_impl() {
  local index name file
  index="$1"
  name="$(service_name "${index}")"
  file="${PROVIDER_PRESS_DIR}/${name}Impl.java"
  {
    license_header
    cat <<EOF

package ${PROVIDER_PACKAGE};

import ${API_PACKAGE}.${name};
import org.apache.dubbo.config.annotation.DubboService;
import org.apache.dubbo.rpc.RpcContext;

/**
 * Generated by dubbo-examples/scripts/gen-press-services.sh - do not edit.
 * Metadata padding is injected at export by PressMetadataInjector.
 */
@DubboService(parameters = {
        "press.meta.index", "${index}"
})
public class ${name}Impl implements ${name} {

    @Override
    public String echo(String value) {
        return "${name}: " + value + " (provider port: " + RpcContext.getContext().getLocalPort() + ")";
    }
}
EOF
  } >"${file}"
}

current_count() {
  local count
  count=$(find "${API_PRESS_DIR}" -maxdepth 1 -name 'PressService*.java' 2>/dev/null | wc -l | tr -d ' ')
  echo "${count:-0}"
}

do_gen() {
  local target i name
  target="${1:-}"
  if [[ -z "${target}" || ! "${target}" =~ ^[0-9]+$ ]]; then
    echo "gen requires a non-negative service count" >&2
    exit 1
  fi
  if [[ "${target}" -eq 0 ]]; then
    do_clean
    return
  fi

  mkdir -p "${API_PRESS_DIR}" "${PROVIDER_PRESS_DIR}"

  for file in "${API_PRESS_DIR}"/PressService*.java; do
    [[ -e "${file}" ]] || continue
    name="$(basename "${file}" .java)"
    i=$((10#${name#PressService}))
    if [[ "${i}" -gt "${target}" ]]; then
      rm -f "${file}" "${PROVIDER_PRESS_DIR}/${name}Impl.java"
    fi
  done

  for ((i = 1; i <= target; i++)); do
    generate_interface "${i}"
    generate_impl "${i}"
  done

  echo "generated ${target} press services"
  echo "  interfaces: ${API_PRESS_DIR}"
  echo "  impls     : ${PROVIDER_PRESS_DIR}"
  echo "  padding   : edit PressMetadataPadding.DEFAULT_BYTES or set PRESS_METADATA_BYTES"
}

do_clean() {
  rm -f "${API_PRESS_DIR}"/PressService*.java "${PROVIDER_PRESS_DIR}"/PressService*Impl.java
  if [[ -d "${PROVIDER_PRESS_DIR}" ]] && [[ -z "$(ls -A "${PROVIDER_PRESS_DIR}" 2>/dev/null || true)" ]]; then
    rmdir "${PROVIDER_PRESS_DIR}"
  fi
  echo "cleaned generated PressService* sources (PressMetadataPadding kept)"
}

do_build() {
  (cd "${REPO_ROOT}" && mvn -q -pl "${PROVIDER_MODULE}" -am package -DskipTests -Dmaven.javadoc.skip=true -Dgpg.skip=true)
  echo "build ok"
}

case "${1:-}" in
  gen)
    do_gen "${2:-}"
    ;;
  count)
    echo "$(current_count) press services generated"
    ;;
  clean)
    do_clean
    ;;
  build)
    do_build
    ;;
  *)
    usage
    ;;
esac
